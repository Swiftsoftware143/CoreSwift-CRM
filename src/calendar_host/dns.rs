//! DNS tooling for a workspace address (David, 2026-11-23).
//!
//! > *"you got to have some DNS tooling … and also have instructions where users can get the DNS
//! > information to put in Cloudflare"*.
//!
//! A workspace address under the platform's own domain needs no DNS work at all: the wildcard answers
//! it. Pointing the customer's OWN domain at it does, because their DNS lives in their account, not
//! here. So this module hands the owner the exact records to paste, and — more useful — CHECKS them,
//! because "add a CNAME" without a verdict is a support ticket.
//!
//! What the records have to achieve, and why they look the way they do:
//!
//! * The origin certificate carries `*.coreswiftcrm.com` and nothing of the customer's, so the
//!   customer's name must be **proxied through Cloudflare** (orange cloud). The edge terminates TLS and
//!   dials the origin over plain HTTP — the same shape every business booking host on this box already
//!   uses. A grey-clouded record would fail the TLS handshake at the origin.
//! * `CNAME → <workspace>.<system domain>` is preferred: it follows the platform address if it ever
//!   moves. `A → <origin address>` is offered for a provider that will not allow a CNAME on an apex
//!   name.
//! * The host must also answer HERE — a vhost per custom domain, generated by
//!   `bin/coreswift-custom-domain-applier.sh` from the same rows. The record alone is not enough, and
//!   the check says which of the two is missing.

use axum::{
    extract::{Extension, Path, State},
    response::IntoResponse,
    Json,
};
use serde_json::json;
use uuid::Uuid;

use super::handlers::require_account_admin;
use super::{public_url, system_domain};
use crate::auth::models::Claims;
use crate::errors::{ApiResult, AppError};
use crate::AppState;

/// The public address of this origin. Written down once: a record that points at the wrong address is
/// the commonest way a custom domain "does not work".
const ORIGIN_ADDRESS: &str = "209.222.97.179";

/// `GET /api/calendar-host/workspaces/:id/dns` — the records to paste, and a live verdict on them.
pub async fn workspace_dns(
    State(s): State<AppState>,
    Extension(c): Extension<Claims>,
    Path(workspace_id): Path<Uuid>,
) -> ApiResult<impl IntoResponse> {
    let tenant_id = require_account_admin(&c)?;
    let system = system_domain(&s);

    let workspace: Option<String> =
        sqlx::query_scalar("SELECT name FROM workspaces WHERE id = $1 AND tenant_id = $2")
            .bind(workspace_id)
            .bind(tenant_id)
            .fetch_optional(&s.db)
            .await?;
    let workspace = workspace.ok_or_else(|| AppError::NotFound("Workspace not found".into()))?;

    let row: Option<(String, Option<String>, Option<String>)> = sqlx::query_as(
        "SELECT subdomain, custom_domain, custom_domain_status FROM workspace_hosts \
          WHERE tenant_id = $1 AND workspace_id = $2",
    )
    .bind(tenant_id)
    .bind(workspace_id)
    .fetch_optional(&s.db)
    .await?;
    let Some((subdomain, custom_domain, status)) = row else {
        return Err(AppError::Validation(
            "Give this workspace an address first — the DNS records point the domain at it.".into(),
        ));
    };
    let platform_host = format!("{subdomain}.{system}");

    // The label the customer types in their DNS provider is the part of their domain that is NOT the
    // zone. `palmbaypulse.com` is `@`; `www.palmbaypulse.com` is `www`.
    let (record_name, zone_guess) = match custom_domain.as_deref() {
        Some(d) => split_label(d),
        None => ("@".to_string(), String::new()),
    };

    let records = json!([
        {
            "type": "CNAME",
            "name": record_name,
            "value": platform_host,
            "ttl": "Auto",
            "proxied": true,
            "why": "Preferred: it follows the platform address if that ever changes. Cloudflare must be orange-clouded (proxied) — the origin certificate covers the platform domain, not yours.",
        },
        {
            "type": "A",
            "name": record_name,
            "value": ORIGIN_ADDRESS,
            "ttl": "Auto",
            "proxied": true,
            "why": "Use this instead of the CNAME only if your provider will not allow a CNAME on this name (usually the apex).",
        },
    ]);

    // The verdict: does the name resolve, does it reach THIS app, and does the app recognise the
    // workspace? Each answer names the step that is still missing rather than a bare pass/fail.
    let mut check = json!({
        "domain": custom_domain,
        "resolves": false,
        "addresses": Vec::<String>::new(),
        "http_status": serde_json::Value::Null,
        "answered_by_app": false,
        "workspace_matched": serde_json::Value::Null,
        "verdict": "No custom domain is saved for this workspace yet, so there is nothing to check.",
    });

    if let Some(domain) = custom_domain.clone() {
        let addrs: Vec<String> = match tokio::net::lookup_host((domain.as_str(), 443u16)).await {
            Ok(iter) => iter.map(|a| a.ip().to_string()).collect(),
            Err(_) => Vec::new(),
        };
        let resolves = !addrs.is_empty();

        // Ask the name itself, over https, what workspace it serves. This is the only check that
        // proves the whole chain: DNS, edge TLS, the origin vhost, and the app's own resolution.
        let mut http_status: Option<u16> = None;
        let mut matched: Option<serde_json::Value> = None;
        let mut answered = false;
        let client = reqwest::Client::builder()
            .timeout(std::time::Duration::from_secs(12))
            .build();
        if let Ok(client) = client {
            let url = format!("https://{domain}/api/public/calendar/site");
            if let Ok(resp) = client.get(&url).send().await {
                http_status = Some(resp.status().as_u16());
                if let Ok(body) = resp.json::<serde_json::Value>().await {
                    answered = body.get("host").is_some();
                    matched = body.get("host").and_then(|h| h.get("subdomain")).cloned();
                }
            }
        }

        let verdict = if !resolves {
            "The name does not resolve yet. Add the record above at your DNS provider, then check again — propagation is usually a minute or two, but a newly added zone can take longer."
                .to_string()
        } else if status.as_deref() != Some("verified") && !answered {
            format!(
                "The name resolves but nothing here answered for it. The record is right; the address is not connected to this workspace on our side yet. Reply to support with this page and it will be switched on: {platform_host}"
            )
        } else if answered {
            format!("Live: {domain} serves this workspace's calendars over https.")
        } else {
            format!(
                "The name reaches the platform but answered {}. Check the Cloudflare proxy is ON (orange cloud) and the SSL mode is Flexible.",
                http_status.unwrap_or(0)
            )
        };

        check = json!({
            "domain": custom_domain,
            "resolves": resolves,
            "addresses": addrs,
            "http_status": http_status,
            "answered_by_app": answered,
            "workspace_matched": matched,
            "verdict": verdict,
        });

        // A real request arriving on the name IS the proof, so record it — the same rule the public
        // site applies when it marks a custom domain verified.
        if answered && status.as_deref() != Some("verified") {
            let _ = sqlx::query(
                "UPDATE workspace_hosts SET custom_domain_status = 'verified', \
                        custom_domain_checked_at = now(), custom_domain_last_error = NULL, \
                        updated_at = now() \
                  WHERE tenant_id = $1 AND workspace_id = $2",
            )
            .bind(tenant_id)
            .bind(workspace_id)
            .execute(&s.db)
            .await;
        } else if !resolves {
            let _ = sqlx::query(
                "UPDATE workspace_hosts SET custom_domain_status = 'pending', \
                        custom_domain_checked_at = now(), updated_at = now() \
                  WHERE tenant_id = $1 AND workspace_id = $2",
            )
            .bind(tenant_id)
            .bind(workspace_id)
            .execute(&s.db)
            .await;
        }
    }

    Ok(Json(json!({
        "workspace": workspace,
        "workspace_id": workspace_id,
        "platform_host": platform_host,
        "platform_url": public_url(&subdomain, None, &system),
        "custom_domain": custom_domain,
        "custom_domain_status": status,
        "dns_zone_guess": zone_guess,
        "records": records,
        "check": check,
        "where": {
            "cloudflare": "Cloudflare dashboard → your domain → DNS → Records → Add record. Pick the type and name above, paste the target, and leave Proxied ON (orange cloud). Then SSL/TLS → Overview → set the mode to Flexible.",
            "other_providers": "Any provider works: create the same type/name/target. If they hide the proxy toggle, the name must instead be pointed with the proxy on at Cloudflare, because the certificate here covers the platform domain only.",
        },
    })))
}

/// Split a domain into the record name and the zone a provider will show it under.
fn split_label(domain: &str) -> (String, String) {
    let host = domain.trim().trim_end_matches('.').to_ascii_lowercase();
    let labels: Vec<&str> = host.split('.').collect();
    if labels.len() <= 2 {
        // An apex: the provider shows it as `@` under the zone it already holds.
        return ("@".to_string(), host);
    }
    let name = labels[0].to_string();
    (name, labels[1..].join("."))
}
